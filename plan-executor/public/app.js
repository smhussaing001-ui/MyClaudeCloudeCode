function nowCard(sched) {
  const active = S.db.active;
  if (active) {
    const t = taskById(active.taskId);
    const plan = planById(t?.planId);
    const est = t?.estimateMin || 0;
    const done = (t?.actualMin || 0) + (Date.now() - Date.parse(active.startedAt)) / 60000;
    const pct = est ? Math.min(100, (done / est) * 100) : 0;
    return `
    <section class="card now-card" style="--now-color:${plan?.color || "var(--accent)"}">
      <div>
        <div class="label">Executing now${plan ? ` · ${esc(plan.title)}` : ""}</div>
        <div class="title">${esc(t?.title)}</div>
        ${isHabit(t) ? "" : `<div class="small muted">${fmtDur(t.actualMin || 0)} logged before this session · estimate ${fmtDur(est)}</div>
        <div class="progress" style="margin-top:6px"><span data-progress style="width:${pct}%"></span></div>`}
        <div class="row" style="margin-top:10px">
          <button class="btn primary" data-action="complete" data-id="${t?.id}">✓ Done</button>
          <button class="btn" data-action="stop">❚❚ Pause</button>
        </div>
      </div>
      <div class="timer" data-timer="${active.startedAt}">0:00</div>
    </section>`;
  }
  if (!sched) return "";
  const n = nowMin();
  const tasks = sched.blocks.filter((b) => b.kind === "task" && blockStatus(b) === "todo");
  const current = isToday() ? tasks.find((b) => toMin(b.start) <= n && toMin(b.end) > n) : null;
  const next = current || tasks.find((b) => !isToday() || toMin(b.start) > n);
  const missed = sched.blocks.filter((b) => blockStatus(b) === "missed").length;
  if (!next) {
    return `<section class="card now-card"><div><div class="label">Status</div><div class="title">${tasks.length ? "Nothing left to start" : "All scheduled work is done 🎉"}</div>
      ${missed ? `<div class="small warn-item">${missed} block${missed > 1 ? "s" : ""} slipped — replan to fit them back in.</div>` : ""}</div></section>`;
  }
  const t = taskById(next.taskId);
  return `
  <section class="card now-card" style="--now-color:${next.color}">
    <div>
      <div class="label">${current ? `Up now · until ${next.end}` : `Next · ${next.start}`}${planById(next.planId) ? ` · ${esc(planById(next.planId).title)}` : ""}</div>
      <div class="title">${esc(next.title)}</div>
      ${t?.notes ? `<div class="small muted">${esc(t.notes)}</div>` : ""}
      ${missed ? `<div class="small warn-item">${missed} earlier block${missed > 1 ? "s" : ""} slipped — <a href="#" data-action="replan">replan</a> to fit ${missed > 1 ? "them" : "it"} back in.</div>` : ""}
      <div class="row" style="margin-top:10px">
        <button class="btn primary" data-action="start" data-id="${next.taskId}">▶ Start${current ? "" : " early"}</button>
        <button class="btn" data-action="complete" data-id="${next.taskId}">✓ Mark done</button>
        <button class="btn ghost" data-action="defer" data-id="${next.taskId}">Push to tomorrow</button>
      </div>
    </div>
    ${current ? `<div class="timer" data-countdown="${next.end}" title="Time left in this block">0:00</div>` : ""}
  </section>`;
}

function timeline(sched, settings) {
  const PX = 1.1;
  const blocks = sched.blocks;
  const start = Math.min(toMin(settings.dayStart), ...blocks.map((b) => toMin(b.start)));
  const end = Math.max(toMin(settings.dayEnd), ...blocks.map((b) => toMin(b.end)));
  const first = Math.floor(start / 60) * 60;
  const last = Math.ceil(end / 60) * 60;
  let html = `<div class="timeline" style="height:${(last - first) * PX}px">`;
  for (let h = first; h <= last; h += 60) {
    html += `<div class="hour" style="top:${(h - first) * PX}px"><span>${fromMin(h)}</span></div>`;
  }
  for (const b of blocks) {
    const top = (toMin(b.start) - first) * PX;
    const height = Math.max(16, (toMin(b.end) - toMin(b.start)) * PX - 2);
    const status = blockStatus(b);
    const cls = b.kind === "task" ? `task ${status}` : b.kind;
    const label = b.kind === "task" ? `${status === "done" ? "✓ " : status === "running" ? "▶ " : ""}${esc(b.title)}` : esc(b.title);
    const why = b.reasons?.length ? ` — ${b.reasons.join(", ")}` : "";
    html += `<div class="block ${cls}" style="top:${top}px;height:${height}px;--c:${b.color || "var(--muted)"}"
      ${b.kind === "task" ? `data-action="block" data-id="${b.taskId}" data-start="${b.start}" data-end="${b.end}"` : ""}
      title="${esc(`${b.start}–${b.end} ${b.title}${why}`)}">
      <span class="time">${b.start}</span><span class="t">${label}</span>${b.partial ? `<span class="small muted">(part)</span>` : ""}
    </div>`;
  }
  if (isToday()) {
    const n = nowMin();
    if (n >= first && n <= last) html += `<div class="now-line" data-nowline style="top:${(n - first) * PX}px" data-first="${first}"></div>`;
  }
  return `${html}</div>`;
}

