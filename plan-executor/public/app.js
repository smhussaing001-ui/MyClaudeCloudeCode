// ---- Utilities ---------------------------------------------------------------

function localDate(d = new Date()) {
  return d.toLocaleDateString("en-CA"); // YYYY-MM-DD in the viewer's timezone
}
function nowMin() {
  const d = new Date();
  return d.getHours() * 60 + d.getMinutes() + d.getSeconds() / 60;
}
const toMin = (s) => {
  const [h, m] = s.split(":").map(Number);
  return h * 60 + m;
};
const fromMin = (m) => `${String(Math.floor(m / 60)).padStart(2, "0")}:${String(Math.floor(m % 60)).padStart(2, "0")}`;
function addDays(date, n) {
  const d = new Date(`${date}T12:00:00`);
  d.setDate(d.getDate() + n);
  return localDate(d);
}
function fmtDur(min) {
  min = Math.round(min);
  if (min < 60) return `${min}m`;
  return `${Math.floor(min / 60)}h${min % 60 ? ` ${min % 60}m` : ""}`;
}
function fmtClock(sec) {
  sec = Math.max(0, Math.floor(sec));
  const h = Math.floor(sec / 3600);
  const m = Math.floor((sec % 3600) / 60);
  const s = sec % 60;
  return `${h ? `${h}:` : ""}${String(m).padStart(h ? 2 : 1, "0")}:${String(s).padStart(2, "0")}`;
}
function fmtDate(date) {
  return new Date(`${date}T12:00:00`).toLocaleDateString(undefined, { weekday: "short", month: "short", day: "numeric" });
}
const esc = (s) =>
  String(s ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]);
const isToday = () => S.date === localDate();
const taskById = (id) => S.db.tasks.find((t) => t.id === id);
const planById = (id) => S.db.plans.find((p) => p.id === id);
const isHabit = (t) => Boolean(t?.repeat);
const taskDone = (t, date = S.date) => (isHabit(t) ? (t.doneDates || []).includes(date) : t?.status === "done");

async function api(method, url, body) {
  const res = await fetch(url, {
    method,
    headers: body ? { "Content-Type": "application/json" } : {},
    body: body ? JSON.stringify(body) : undefined,
  });
  const data = await res.json().catch(() => ({}));
  if (!res.ok) throw new Error(data.error || `Request failed (${res.status})`);
  return data;
}

function toast(msg, ms = 3500) {
  document.querySelector(".toast")?.remove();
  const el = document.createElement("div");
  el.className = "toast";
  el.textContent = msg;
  document.body.append(el);
  setTimeout(() => el.remove(), ms);
}

async function refresh() {
  S.db = await api("GET", "/api/state");
  const pill = document.getElementById("ai-pill");
  pill.textContent = S.db.aiConfigured ? "Claude connected" : "AI: templates";
  pill.className = `pill ${S.db.aiConfigured ? "ok" : ""}`;
  pill.title = S.db.aiConfigured ? "Plans and coaching are generated by Claude" : "Set ANTHROPIC_API_KEY and restart to enable Claude";
  S.forecast = await api("GET", `/api/forecast?date=${S.date}${isToday() ? `&nowMin=${Math.floor(nowMin())}` : ""}`);
  if (S.view === "insights") S.insights = await api("GET", `/api/insights?date=${S.date}`);
  render();
}

/** Run an action, surface errors as a toast, then reload state. */
async function act(fn, { reload = true } = {}) {
  try {
    const out = await fn();
    if (reload) await refresh();
    return out;
  } catch (err) {
    toast(err.message);
  }
}

