function barChart(series) {
  const W = 720, H = 220, L = 40, B = 24, T = 10;
  const max = Math.max(60, ...series.flatMap((d) => [d.plannedMin, d.focusMin]));
  const step = max > 360 ? 120 : 60;
  const top = Math.ceil(max / step) * step;
  const y = (v) => T + (H - T - B) * (1 - v / top);
  const groupW = (W - L) / series.length;
  const barW = Math.min(14, (groupW - 8) / 2);
  let svg = `<svg viewBox="0 0 ${W} ${H}" role="img" aria-label="Scheduled versus logged focus minutes per day">`;
  for (let v = 0; v <= top; v += step) {
    svg += `<line class="grid" x1="${L}" x2="${W}" y1="${y(v)}" y2="${y(v)}"/><text class="axis" x="${L - 6}" y="${y(v) + 3}" text-anchor="end">${v / 60}h</text>`;
  }
  const bar = (x, v, color) => {
    if (!v) return "";
    const h = y(0) - y(v);
    const r = Math.min(4, h, barW / 2);
    // rounded data-end, square baseline
    return `<path fill="${color}" d="M${x},${y(0)} V${y(v) + r} Q${x},${y(v)} ${x + r},${y(v)} H${x + barW - r} Q${x + barW},${y(v)} ${x + barW},${y(v) + r} V${y(0)} Z"/>`;
  };
  series.forEach((d, i) => {
    const cx = L + groupW * i + groupW / 2;
    svg += `<g>${bar(cx - barW - 1, d.plannedMin, "var(--series-1)")}${bar(cx + 1, d.focusMin, "var(--series-2)")}`;
    svg += `<rect data-tip="${esc(`${fmtDate(d.date)} · scheduled ${fmtDur(d.plannedMin)} · logged ${fmtDur(d.focusMin)}`)}" x="${cx - groupW / 2}" y="${T}" width="${groupW}" height="${H - T - B}" fill="transparent"/></g>`;
    if (i % 2 === series.length % 2 || series.length < 8) {
      const dt = new Date(`${d.date}T12:00:00`);
      svg += `<text class="axis" x="${cx}" y="${H - 8}" text-anchor="middle">${dt.getMonth() + 1}/${dt.getDate()}</text>`;
    }
  });
  return `<div class="chart">${svg}</svg></div>`;
}

function attachChartHover() {
  const chart = document.querySelector(".chart");
  if (!chart) return;
  const tip = document.createElement("div");
  tip.className = "tooltip";
  tip.hidden = true;
  chart.append(tip);
  chart.addEventListener("pointermove", (e) => {
    const target = e.target.closest("[data-tip]");
    if (!target) return (tip.hidden = true);
    const box = chart.getBoundingClientRect();
    tip.textContent = target.dataset.tip;
    tip.hidden = false;
    tip.style.left = `${Math.min(Math.max(e.clientX - box.left, 90), box.width - 90)}px`;
    tip.style.top = `${e.clientY - box.top}px`;
  });
  chart.addEventListener("pointerleave", () => (tip.hidden = true));
}

