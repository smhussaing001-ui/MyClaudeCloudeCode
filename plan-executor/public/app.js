      title: f.title.value,
      notes: f.notes.value,
      planId: f.planId.value || null,
      milestoneId: f.milestoneId.value || null,
      estimateMin: Number(f.estimateMin.value),
      priority: Number(f.priority.value),
      energy: f.energy.value,
      repeat: f.repeat.value || null,
      deadline: f.deadline.value || null,
      earliestDate: f.earliestDate.value || null,
      preferredTime: f.preferredTime.value || null,
      pinned: f.pinDate.value && f.pinStart.value ? { date: f.pinDate.value, start: f.pinStart.value } : null,
