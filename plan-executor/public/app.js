function blockStatus(b) {
  if (b.kind !== "task") return b.kind;
  const t = taskById(b.taskId);
  if (!t) return "gone";
  if (taskDone(t)) return "done";
  if (S.db.active?.taskId === b.taskId) return "running";
  if (isToday() && toMin(b.end) <= nowMin()) return "missed";
  return "todo";
}

