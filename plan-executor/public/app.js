function taskRow(t) {
  const done = taskDone(t);
  const deps = (t.dependsOn || []).map(taskById).filter(Boolean);
  const blocked = deps.some((d) => d.status !== "done");
  return `
  <div class="task-row ${done ? "done" : ""}">
    <input type="checkbox" ${done ? "checked" : ""} data-action="toggle-done" data-id="${t.id}" aria-label="Done" />
    <span class="name" data-action="edit-task" data-id="${t.id}">${esc(t.title)}
      ${blocked ? `<span class="small muted" title="Waits for: ${esc(deps.map((d) => d.title).join(", "))}"> ⧗ waiting</span>` : ""}</span>
    <span class="meta">
      ${isHabit(t) ? `<span class="tag">↻ ${t.repeat}${t.preferredTime ? ` @ ${t.preferredTime}` : ""}</span>` : ""}
      <span class="tag ${t.energy === "high" ? "high" : ""}">${t.energy || "medium"}</span>
      <span class="tag">P${t.priority}</span>
      ${t.deadline ? `<span class="tag">due ${fmtDate(t.deadline)}</span>` : ""}
      <span>${!isHabit(t) && t.actualMin ? `${fmtDur(t.actualMin)} / ` : ""}${fmtDur(t.estimateMin)}</span>
    </span>
  </div>`;
}

